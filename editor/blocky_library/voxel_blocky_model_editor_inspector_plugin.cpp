namespace zylann::voxel {

void VoxelBlockyModelEditorInspectorPlugin::set_undo_redo(EditorUndoRedoManager *urm) {
	_undo_redo = urm;
}

bool VoxelBlockyModelEditorInspectorPlugin::_zn_can_handle(const Object *p_object) const {
	return Object::cast_to<VoxelBlockyModel>(p_object) != nullptr;
}

void VoxelBlockyModelEditorInspectorPlugin::_zn_parse_begin(Object *p_object) {
	const VoxelBlockyModel *model_ptr = Object::cast_to<VoxelBlockyModel>(p_object);
	ZN_ASSERT_RETURN(model_ptr != nullptr);

	Ref<VoxelBlockyModel> model(model_ptr);

	// Name of the model
	{
		HBoxContainer *name_container = memnew(HBoxContainer);

		Label *label = memnew(Label);
		label->set_text(ZN_TTR("Name"));
		name_container->add_child(label);

		LineEdit *line_edit = memnew(LineEdit);
		line_edit->set_h_size_flags(Control::SIZE_EXPAND_FILL);
		line_edit->set_text(model->get_name());
		line_edit->set_placeholder(ZN_TTR("<unnamed>"));

		if (Object::cast_to<VoxelBlockyModelRotated>(model_ptr) != nullptr) {
			// Generated by "Update rotation variants", from the name of the source model
			line_edit->set_editable(false);
			line_edit->set_tooltip_text(ZN_TTR("Generated from the name of the source model."));
		} else {
			line_edit->connect(
					"text_submitted",
					callable_mp(this, &VoxelBlockyModelEditorInspectorPlugin::on_name_text_submitted).bind(model)
			);
			line_edit->connect(
					"focus_exited",
					callable_mp(this, &VoxelBlockyModelEditorInspectorPlugin::on_name_focus_exited)
							.bind(model, line_edit)
			);
		}

		name_container->add_child(line_edit);

		add_custom_control(name_container);
	}

	VoxelBlockyModelViewer *viewer = memnew(VoxelBlockyModelViewer);
	viewer->set_model(model);
	viewer->set_undo_redo(_undo_redo);
	add_custom_control(viewer);
	return;
}

void VoxelBlockyModelEditorInspectorPlugin::apply_name(Ref<VoxelBlockyModel> model, const String &new_name) {
	ZN_ASSERT_RETURN(model.is_valid());

	const String old_name = model->get_name();

	if (new_name == old_name) {
		return;
	}

	if (_undo_redo == nullptr) {
		model->set_name(new_name);
		return;
	}

	EditorUndoRedoManager &ur = *_undo_redo;

	ur.create_action(ZN_TTR("Rename model"));
	ur.add_do_method(model.ptr(), "set_name", new_name);
	ur.add_undo_method(model.ptr(), "set_name", old_name);
	ur.commit_action();
}

void VoxelBlockyModelEditorInspectorPlugin::on_name_text_submitted(const String &text, Ref<VoxelBlockyModel> model) {
	apply_name(model, text);
}

void VoxelBlockyModelEditorInspectorPlugin::on_name_focus_exited(Ref<VoxelBlockyModel> model, LineEdit *line_edit) {
	ZN_ASSERT_RETURN(line_edit != nullptr);

	apply_name(model, line_edit->get_text());
}

} // namespace zylann::voxel
